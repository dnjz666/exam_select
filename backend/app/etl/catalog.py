class Major(NamedTuple):
    name: str
    category: str
    discipline: str
    subject_mode: str
    subjects: tuple[str, ...]


def iter_majors() -> Iterator[Major]:
    """按 (门类, 专业类) 排序、专业名册顺序稳定遍历全部专业。"""
    for (category, discipline) in sorted(_RAW_MAJORS):
        rule = SUBJECT_RULES_BY_DISCIPLINE.get(discipline) or SUBJECT_RULES_BY_CATEGORY[category]
        mode, subjects = rule
        for name in _RAW_MAJORS[(category, discipline)]:
            yield Major(name, category, discipline, mode, subjects)


